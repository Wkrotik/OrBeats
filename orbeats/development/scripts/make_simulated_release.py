#!/usr/bin/env python3
"""Build a SIMULATED RELEASE folder from the working tree (M12 validation).

Mirrors the plugin-build.yml release-zip layout (minus the CI-generated
coverage report) so the fresh-user flow can be validated BEFORE tagging —
including the "cannot see any ps4_dump" property: the folder is
self-contained, its config paths resolve PROJECT_ROOT-relatively (Exp 271),
and game_dump_dir points at a deliberately-absent path so the
"Use the extracted cache" switch is validated for real.

Usage:
    python3 development/scripts/make_simulated_release.py <target-dir> \
        [--ps4-ip 192.168.100.117] [--from-repo /workspace]

The target gets a ready-to-run webapp (cd webapp && python3 server.py), a
freshly copied plugin pair (build first: make -B && make -B DEBUG=1), the
tools, all feature docs, the example scripts, and a pre-made ps4_config.json
pointing at the given PS4 with game_dump_dir = ./ps4_dump_local (ABSENT by
design). Nothing from /workspace's ps4_dump is referenced or copied.
"""
import argparse
import json
import os
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
BSD = REPO / "orbeats"


def build(target: Path, ps4_ip: str) -> int:
    if target.exists():
        print(f"❌ {target} already exists — remove it first (it is disposable).")
        return 1

    missing = [p for p in (BSD / "orbeats.prx",
                            BSD / "orbeats_debug.prx")]
    missing = [p for p in missing if not p.exists()]
    if missing:
        print("❌ plugin binaries missing — build first:  make -B && make -B DEBUG=1")
        for p in missing:
            print(f"   {p}")
        return 1

    # ── the release-zip layout (workflow lines 158-243, minus coverage) ──
    dirs = ["plugins", "webapp", "tools", "docs/features",
            "docs/examples", "docs/example-scripts"]
    for d in dirs:
        (target / d).mkdir(parents=True, exist_ok=True)

    shutil.copy2(BSD / "orbeats.prx", target / "plugins")
    shutil.copy2(BSD / "orbeats_debug.prx", target / "plugins")

    for name in ("CHANGELOG-PLUGIN.md", "CHANGELOG-PIPELINE.md", "VERSION",
                 "ps4_config.example.json"):
        shutil.copy2(BSD / name, target / name)
    shutil.copy2(REPO / "README.md", target / "README.md")
    shutil.copy2(BSD / "README.md", target / "PIPELINE-README.md")

    backup = REPO / "backup-orbeats-files.py"
    if not backup.exists():
        backup = BSD / "tools" / "backup-orbeats-files.py"
    shutil.copy2(backup, target / "backup-orbeats-files.py")

    shutil.copy2(BSD / "beat_saber_song_ids.json", target / "beat_saber_song_ids.json")
    shutil.copy2(REPO / "requirements.txt", target / "requirements.txt")

    for doc in sorted((BSD / "docs" / "features").glob("*.md")):
        shutil.copy2(doc, target / "docs" / "features")
    for doc in ("camellia-pack-example.md",):
        src = BSD / "docs" / doc
        if src.exists():
            shutil.copy2(src, target / "docs" / "examples")
    howto = BSD / "docs" / "how-to-replace-pack.md"
    if howto.exists():
        shutil.copy2(howto, target / "docs")
    for script in sorted((REPO / "docs" / "example-scripts").glob("example_*")):
        shutil.copy2(script, target / "docs" / "example-scripts")
    for proc in ("release-validation-test-procedure.md",
                 "release-validation-test-procedure.sh"):
        src = REPO / ".agent" / "docs" / proc
        if src.exists():
            shutil.copy2(src, target / "docs")

    # tools/ + webapp/ — mirrors of the source trees (no __pycache__)
    def copytree_clean(src: Path, dst: Path):
        shutil.copytree(src, dst, dirs_exist_ok=True,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc",
                                                      "node_modules", ".git"))
    copytree_clean(BSD / "tools", target / "tools")
    copytree_clean(BSD / "webapp", target / "webapp")

    # ── generated templates (the workflow's single-source patterns) ──
    # features.json: FROM DEFAULT_FEATURES (Exp 278i — never hardcode here)
    sys.path.insert(0, str(BSD / "tools"))
    from full_custom_song_pipeline import DEFAULT_FEATURES  # noqa: E402
    with open(target / "features.json", "w") as f:
        json.dump(DEFAULT_FEATURES, f, indent=2)
        f.write("\n")

    # redirects.json: the clean-slate template (as the workflow generates)
    (target / "redirects.json").write_text(json.dumps(
        {"comment": "OrBeats — song redirects (regenerated by the "
                    "pipeline on every deploy)", "redirects": {}}, indent=2) + "\n")

    # plugins.ini: the GoldHEN template
    (target / "plugins.ini").write_text(
        "[CUSA12878]\norbeats.prx=1\n")

    # ── the pre-made ps4_config.json (fresh-user simulation) ──
    # game_dump_dir points at a DELIBERATELY ABSENT path: any song build
    # before the extraction+pull correctly fails; "Use the extracted cache"
    # then switches it to ./game_data (the real validation of the switch).
    cfg = {
        "comment": "OrBeats — simulated release validation config",
        "ps4": {"ip": ps4_ip, "ftp_port": 2121,
                "ftp_user": "anonymous", "ftp_password": ""},
        "title": {"id": "CUSA12878", "patch_suffix": "-patch"},
        "paths": {
            "afr_base": "/data/GoldHEN/AFR",
            "afr_target_suffix": "_v3.bundle",
            "game_dump_dir": "./ps4_dump_local",
            "game_data_dir": "./game_data",
            "template_dir": "Media/StreamingAssets/BeatmapLevelsData",
            "output_dir": "./custom_songs",
        },
        "pipeline": {"default_target": "startmeup", "sample_rate": 44100},
        "pack_modes": {"build_dir": "./pack_modes_bundles",
                       "song_ids_path": "./beat_saber_song_ids.json",
                       "patched_catalog_local": "./catalog_pack_modes.json"},
        "mass_deploy": {"bundle_dir": "./mass_bundles", "slots": []},
        "webapp": {"browsable_backups": True},
    }
    with open(target / "ps4_config.json", "w") as f:
        json.dump(cfg, f, indent=4)
        f.write("\n")

    import re
    m = re.search(rb"OrBeats v(\d+\.\d+) started",
                   (target / "plugins" / "orbeats.prx").read_bytes())
    plugin_ver = "v" + m.group(1).decode() if m else "unknown"
    print(f"✅ Simulated release built at {target}")
    print(f"   versions: plugin {plugin_ver} pair · pipeline "
          f"{(target / 'VERSION').read_text().strip()} · webapp "
          f"{(target / 'webapp' / 'VERSION').read_text().strip()}")
    print(f"   config: PS4 {ps4_ip}:2121 · game_dump_dir=./ps4_dump_local (ABSENT by design)")
    print(f"   run:    cd {target}/webapp && python3 server.py --port 8799")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("target", type=Path)
    ap.add_argument("--ps4-ip", default="192.168.100.117")
    args = ap.parse_args()
    return build(args.target.resolve(), args.ps4_ip)


if __name__ == "__main__":
    sys.exit(main())
